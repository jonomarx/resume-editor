-- One row per stored file (US-010, DESIGN sections 3 and 8). The row is inserted as PENDING before the file is written
-- and becomes COMMITTED in the transaction that commits the row referencing the file. file_key holds the design's `key`
-- (renamed because KEY is a reserved word in some SQL dialects). user_id is derived from the key and has no foreign
-- key: registry rows must outlive account handling and are cleaned by the reconciliation worker (US-070).
CREATE TABLE file_registry (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_key   VARCHAR(600)  NOT NULL,
    uri        VARCHAR(1000) NOT NULL,
    size       BIGINT        NOT NULL,
    sha256     VARCHAR(64)   NOT NULL,
    user_id    BIGINT,
    state      VARCHAR(10)   NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_file_registry_key UNIQUE (file_key),
    CONSTRAINT ck_file_registry_state CHECK (state IN ('PENDING', 'COMMITTED'))
);
CREATE INDEX ix_file_registry_state_created ON file_registry (state, created_at);
