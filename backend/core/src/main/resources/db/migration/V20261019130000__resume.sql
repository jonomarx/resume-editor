-- Master resume and its version history (US-014). The tree lives in a file (FileStorage); these rows hold pointers.
-- job_posting_id is 0 for the master resume; the drafts story (US-060) uses it for the posting a draft belongs to.
CREATE TABLE resume (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT       NOT NULL REFERENCES app_user (id),
    kind           VARCHAR(10)  NOT NULL,
    job_posting_id BIGINT       NOT NULL DEFAULT 0,
    version        BIGINT       NOT NULL,
    content_hash   VARCHAR(64)  NOT NULL,
    storage_uri    VARCHAR(1000) NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_resume_kind CHECK (kind IN ('MASTER', 'DRAFT')),
    CONSTRAINT uq_resume_owner UNIQUE (user_id, kind, job_posting_id)
);

CREATE TABLE resume_version (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resume_id    BIGINT       NOT NULL REFERENCES resume (id),
    version      BIGINT       NOT NULL,
    content_hash VARCHAR(64)  NOT NULL,
    storage_uri  VARCHAR(1000) NOT NULL,
    file_key     VARCHAR(600) NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_resume_version UNIQUE (resume_id, version)
);
