-- Accounts (US-006). username_key is the lower-cased username and carries the unique constraint,
-- so "Ada" and "ada" cannot both exist. Works on both Postgres and H2 (PostgreSQL mode).
CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(40)  NOT NULL,
    username_key  VARCHAR(40)  NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_app_user_username_key UNIQUE (username_key)
);
