-- Tag vocabulary (US-020). Every row carries user_id (multi-user ready).
CREATE TABLE tag (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES app_user (id),
    name       VARCHAR(60)  NOT NULL,
    slug       VARCHAR(80)  NOT NULL,
    category   VARCHAR(20)  NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_tag_user_slug UNIQUE (user_id, slug),
    CONSTRAINT ck_tag_category CHECK (category IN ('language', 'framework', 'domain', 'role_type'))
);

-- Every lookup key of a tag: its own slug (is_alias = false) and its aliases (is_alias = true).
-- One unique constraint over both kinds is what makes "an alias cannot collide with another tag's slug or alias"
-- true even under concurrent writes.
CREATE TABLE tag_key (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id  BIGINT      NOT NULL REFERENCES app_user (id),
    tag_id   BIGINT      NOT NULL REFERENCES tag (id) ON DELETE CASCADE,
    tag_key  VARCHAR(80) NOT NULL,
    is_alias BOOLEAN     NOT NULL,
    CONSTRAINT uq_tag_key_user_key UNIQUE (user_id, tag_key)
);
CREATE INDEX ix_tag_key_tag ON tag_key (tag_id);
