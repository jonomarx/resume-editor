-- Derived index of the tags on the nodes of a resume's CURRENT version (US-021). The version file stays the source of
-- truth; this table is rebuilt in the same transaction that commits a new version row, so it always matches the current
-- tree. user_id is repeated for per-user queries (the matcher, tag usage counts).
CREATE TABLE resume_node_tag (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id   BIGINT      NOT NULL REFERENCES app_user (id),
    resume_id BIGINT      NOT NULL REFERENCES resume (id),
    node_id   VARCHAR(64) NOT NULL,
    tag_id    BIGINT      NOT NULL REFERENCES tag (id) ON DELETE CASCADE,
    CONSTRAINT uq_resume_node_tag UNIQUE (resume_id, node_id, tag_id)
);
CREATE INDEX ix_resume_node_tag_user_tag ON resume_node_tag (user_id, tag_id);
