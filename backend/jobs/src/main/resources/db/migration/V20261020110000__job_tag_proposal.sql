-- Tags the enrichment step wanted but the shared vocabulary does not have (US-040). Postings never get free-text
-- tags: a proposal waits here until the user approves it into the vocabulary, after which re-enrichment links it.
CREATE TABLE job_tag_proposal (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id BIGINT      NOT NULL REFERENCES app_user (id),
    name          VARCHAR(60) NOT NULL,
    slug          VARCHAR(80) NOT NULL,
    category      VARCHAR(20) NOT NULL,
    status        VARCHAR(10) NOT NULL DEFAULT 'pending',
    first_posting_id BIGINT   REFERENCES job_posting (id) ON DELETE SET NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_job_tag_proposal_owner_slug UNIQUE (owner_user_id, slug),
    CONSTRAINT ck_job_tag_proposal_category CHECK (category IN ('language', 'framework', 'domain', 'role_type')),
    CONSTRAINT ck_job_tag_proposal_status CHECK (status IN ('pending', 'approved', 'rejected'))
);
