-- Job pipeline tables (US-030). Every row carries a user id (multi-user ready); works on Postgres and H2 (PostgreSQL mode).

-- Company career page links the user provides.
CREATE TABLE job_source (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL REFERENCES app_user (id),
    name            VARCHAR(120) NOT NULL,
    url             VARCHAR(2048) NOT NULL,
    url_hash        VARCHAR(64)  NOT NULL,
    tier            VARCHAR(20)  NOT NULL DEFAULT 'auto',
    enabled         BOOLEAN      NOT NULL DEFAULT TRUE,
    content_hash    VARCHAR(64),
    last_fetched_at TIMESTAMP WITH TIME ZONE,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_job_source_user_url UNIQUE (user_id, url_hash),
    CONSTRAINT ck_job_source_tier CHECK (tier IN ('auto', 'ats', 'jsonld', 'llm'))
);

-- One posting. source_id is null for one-time (ingested) postings.
CREATE TABLE job_posting (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id          BIGINT       NOT NULL REFERENCES app_user (id),
    source_id              BIGINT       REFERENCES job_source (id) ON DELETE SET NULL,
    origin                 VARCHAR(10)  NOT NULL,
    canonical_url          VARCHAR(2048) NOT NULL,
    url_hash               VARCHAR(64)  NOT NULL,
    content_hash           VARCHAR(64)  NOT NULL,
    dedupe_key             VARCHAR(64)  NOT NULL,
    title                  VARCHAR(300) NOT NULL,
    company                VARCHAR(200) NOT NULL,
    location               VARCHAR(300),
    description            TEXT,
    basic_requirements     TEXT,
    preferred_requirements TEXT,
    season                 VARCHAR(40),
    work_authorization     VARCHAR(120),
    class_year             VARCHAR(40),
    status                 VARCHAR(10)  NOT NULL DEFAULT 'active',
    missed_runs            INT          NOT NULL DEFAULT 0,
    first_seen_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_seen_at           TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at              TIMESTAMP WITH TIME ZONE,
    created_at             TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at             TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_job_posting_owner_url UNIQUE (owner_user_id, url_hash),
    CONSTRAINT ck_job_posting_origin CHECK (origin IN ('crawl', 'ingest')),
    CONSTRAINT ck_job_posting_status CHECK (status IN ('active', 'stale', 'closed'))
);
CREATE INDEX ix_job_posting_owner_status ON job_posting (owner_user_id, status);
CREATE INDEX ix_job_posting_source ON job_posting (source_id);
CREATE INDEX ix_job_posting_dedupe ON job_posting (owner_user_id, dedupe_key);

-- Links to the shared tag vocabulary (never free text).
CREATE TABLE job_posting_tag (
    posting_id BIGINT NOT NULL REFERENCES job_posting (id) ON DELETE CASCADE,
    tag_id     BIGINT NOT NULL REFERENCES tag (id) ON DELETE CASCADE,
    PRIMARY KEY (posting_id, tag_id)
);
CREATE INDEX ix_job_posting_tag_tag ON job_posting_tag (tag_id);

-- Audit trail: one row per source per daily run (also feeds the source health view).
CREATE TABLE crawl_run (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT      NOT NULL REFERENCES app_user (id),
    source_id     BIGINT      NOT NULL REFERENCES job_source (id) ON DELETE CASCADE,
    status        VARCHAR(12) NOT NULL DEFAULT 'running',
    started_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at   TIMESTAMP WITH TIME ZONE,
    tier          VARCHAR(20),
    postings_seen INT         NOT NULL DEFAULT 0,
    added         INT         NOT NULL DEFAULT 0,
    updated       INT         NOT NULL DEFAULT 0,
    staled        INT         NOT NULL DEFAULT 0,
    closed        INT         NOT NULL DEFAULT 0,
    error         TEXT,
    CONSTRAINT ck_crawl_run_status CHECK (status IN ('running', 'ok', 'unchanged', 'failed'))
);
CREATE INDEX ix_crawl_run_source_started ON crawl_run (source_id, started_at);

-- Audit trail for the ingest API. idempotency_key is the URL hash or content hash of the input.
CREATE TABLE ingest_event (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL REFERENCES app_user (id),
    kind            VARCHAR(10)  NOT NULL,
    source_hint     VARCHAR(200),
    idempotency_key VARCHAR(64)  NOT NULL,
    status          VARCHAR(12)  NOT NULL DEFAULT 'pending',
    posting_id      BIGINT       REFERENCES job_posting (id) ON DELETE SET NULL,
    error           TEXT,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    processed_at    TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_ingest_event_user_key UNIQUE (user_id, idempotency_key),
    CONSTRAINT ck_ingest_event_kind CHECK (kind IN ('url', 'html', 'text', 'email')),
    CONSTRAINT ck_ingest_event_status CHECK (status IN ('pending', 'processed', 'failed', 'duplicate'))
);
