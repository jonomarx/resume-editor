-- Aligns the job tables with the OpenAPI v1 contract (0.6.0) and adds ingest tokens. The tables of
-- V20261020100000 have no data yet; statements are plain ALTERs that run on Postgres and H2.

-- Source.extractionTier: ats_feed | json_ld | llm, null before the first crawl.
ALTER TABLE job_source DROP CONSTRAINT ck_job_source_tier;
ALTER TABLE job_source ALTER COLUMN tier DROP DEFAULT;
ALTER TABLE job_source ALTER COLUMN tier DROP NOT NULL;
ALTER TABLE job_source RENAME COLUMN tier TO extraction_tier;
ALTER TABLE job_source ADD CONSTRAINT ck_job_source_tier CHECK (extraction_tier IN ('ats_feed', 'json_ld', 'llm'));

-- CrawlRun.status: running | succeeded | failed | skipped_unchanged.
ALTER TABLE crawl_run DROP CONSTRAINT ck_crawl_run_status;
ALTER TABLE crawl_run ADD CONSTRAINT ck_crawl_run_status CHECK (status IN ('running', 'succeeded', 'failed', 'skipped_unchanged'));
ALTER TABLE crawl_run ALTER COLUMN tier TYPE VARCHAR(20);

-- IngestEvent: status queued | processing | done | failed, an error code and message, and the payload to process.
ALTER TABLE ingest_event DROP CONSTRAINT ck_ingest_event_status;
ALTER TABLE ingest_event ALTER COLUMN status SET DEFAULT 'queued';
ALTER TABLE ingest_event ADD CONSTRAINT ck_ingest_event_status CHECK (status IN ('queued', 'processing', 'done', 'failed'));
ALTER TABLE ingest_event RENAME COLUMN error TO error_message;
ALTER TABLE ingest_event ADD COLUMN error_code VARCHAR(40);
ALTER TABLE ingest_event ADD COLUMN payload TEXT;

-- Per-user, revocable, ingest-only tokens. Only the SHA-256 of the secret is stored.
CREATE TABLE ingest_token (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT       NOT NULL REFERENCES app_user (id),
    label        VARCHAR(60)  NOT NULL,
    token_hash   VARCHAR(64)  NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_used_at TIMESTAMP WITH TIME ZONE,
    revoked_at   TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_ingest_token_hash UNIQUE (token_hash)
);
CREATE INDEX ix_ingest_token_user ON ingest_token (user_id);
